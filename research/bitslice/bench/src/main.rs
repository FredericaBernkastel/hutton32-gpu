/// One byte per cell with a one-cell zero ring: `(w + 2) x (h + 2)` bytes.
#[derive(Clone)]
pub struct ByteGrid {
  pub w: usize,
  pub h: usize,
  pub stride: usize,
  pub cells: Vec<u8>,
}

impl ByteGrid {
  fn new(w: usize, h: usize) -> Self {
    ByteGrid { w, h, stride: w + 2, cells: vec![0; (w + 2) * (h + 2)] }
  }
  fn set(&mut self, x: usize, y: usize, v: u8) {
    self.cells[(y + 1) * self.stride + x + 1] = v;
  }
  fn get(&self, x: usize, y: usize) -> u8 {
    self.cells[(y + 1) * self.stride + x + 1]
  }
}

/// Five bit-planes; every row has one zero word of padding on each side and there is one zero
/// row above and below: `(h + 2) x (w/64 + 2)` words per plane. Bit i of a word is cell i.
#[derive(Clone)]
struct PlaneGrid {
  w: usize,
  h: usize,
  ww: usize,
  planes: [Vec<u64>; 5],
}

impl PlaneGrid {
  fn new(w: usize, h: usize) -> Self {
    assert!(w % 64 == 0, "width must be a multiple of 64");
    let ww = w / 64 + 2;
    PlaneGrid { w, h, ww, planes: std::array::from_fn(|_| vec![0u64; ww * (h + 2)]) }
  }
  fn from_bytes(g: &ByteGrid) -> Self {
    let mut p = PlaneGrid::new(g.w, g.h);
    for y in 0..g.h {
      for x in 0..g.w {
        let v = g.get(x, y);
        let i = (y + 1) * p.ww + 1 + x / 64;
        for k in 0..5 {
          p.planes[k][i] |= (((v >> k) & 1) as u64) << (x % 64);
        }
      }
    }
    p
  }
  fn to_bytes(&self) -> ByteGrid {
    let mut g = ByteGrid::new(self.w, self.h);
    for y in 0..self.h {
      for x in 0..self.w {
        let i = (y + 1) * self.ww + 1 + x / 64;
        let mut v = 0u8;
        for k in 0..5 {
          v |= (((self.planes[k][i] >> (x % 64)) & 1) as u8) << k;
        }
        g.set(x, y, v);
      }
    }
    g
  }
}


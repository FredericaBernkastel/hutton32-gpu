/// Byte-per-cell LUT step. Every state in the grid is < 32, so the index is < 2^25.
#[inline(never)]
fn lut_step(lut: &[u8; LUT_SIZE], src: &ByteGrid, dst: &mut ByteGrid) {
  let (w, h, stride) = (src.w, src.h, src.stride);
  assert!(dst.w == w && dst.h == h && src.cells.len() == stride * (h + 2) && dst.cells.len() == src.cells.len());
  for y in 1..=h {
    let up = &src.cells[(y - 1) * stride..y * stride];
    let cur = &src.cells[y * stride..(y + 1) * stride];
    let dn = &src.cells[(y + 1) * stride..(y + 2) * stride];
    let out = &mut dst.cells[y * stride..(y + 1) * stride];
    for x in 1..=w {
      // SAFETY: 1 <= x <= w and every row slice has w + 2 elements
      let idx = unsafe {
        (*cur.get_unchecked(x - 1) as usize)
          | (*dn.get_unchecked(x) as usize) << 5
          | (*cur.get_unchecked(x + 1) as usize) << 10
          | (*up.get_unchecked(x) as usize) << 15
          | (*cur.get_unchecked(x) as usize) << 20
      };
      let v = lut[idx & (LUT_SIZE - 1)];
      unsafe { *out.get_unchecked_mut(x) = v };
    }
  }
}

/// Form A: same index as the LUT step, but the next state is computed by straight-line code.
#[inline(never)]
fn scalar_grid_step(src: &ByteGrid, dst: &mut ByteGrid) {
  let (w, h, stride) = (src.w, src.h, src.stride);
  assert!(dst.w == w && dst.h == h && src.cells.len() == stride * (h + 2) && dst.cells.len() == src.cells.len());
  for y in 1..=h {
    let up = &src.cells[(y - 1) * stride..y * stride];
    let cur = &src.cells[y * stride..(y + 1) * stride];
    let dn = &src.cells[(y + 1) * stride..(y + 2) * stride];
    let out = &mut dst.cells[y * stride..(y + 1) * stride];
    for x in 1..=w {
      // SAFETY: 1 <= x <= w and every row slice has w + 2 elements
      unsafe {
        let idx = (*cur.get_unchecked(x - 1) as u32)
          | (*dn.get_unchecked(x) as u32) << 5
          | (*cur.get_unchecked(x + 1) as u32) << 10
          | (*up.get_unchecked(x) as u32) << 15
          | (*cur.get_unchecked(x) as u32) << 20;
        *out.get_unchecked_mut(x) = scalar::scalar_step(idx) as u8;
      }
    }
  }
}

/// Bit-sliced step on 256-bit words: one call of the gate network per 256 cells.
#[cfg(target_feature = "avx2")]
#[inline(never)]
fn plane_step_wide(src: &PlaneGrid, dst: &mut PlaneGrid) {
  use std::arch::x86_64::*;
  use wide::W;
  let (h, ww) = (src.h, src.ww);
  assert!(dst.h == h && dst.ww == ww && (ww - 2) % 4 == 0, "row length must be a multiple of 256 cells");
  for k in 0..5 {
    assert!(src.planes[k].len() == ww * (h + 2) && dst.planes[k].len() == ww * (h + 2));
  }
  for y in 1..=h {
    let base = y * ww;
    let mut i = 1;
    while i + 4 <= ww - 1 {
      // SAFETY: words base-ww+i .. base+ww+i+4 and base+i-1 .. base+i+5 lie inside the planes
      // (1 <= i, i + 4 <= ww - 1, one padding row above and below)
      unsafe {
        let ld = |k: usize, at: usize| _mm256_loadu_si256(src.planes[k].as_ptr().add(at) as *const __m256i);
        let c: [W; 5] = std::array::from_fn(|k| wide::u64(ld(k, base + i)));
        let n: [W; 5] = std::array::from_fn(|k| wide::u64(ld(k, base - ww + i)));
        let s: [W; 5] = std::array::from_fn(|k| wide::u64(ld(k, base + ww + i)));
        let e: [W; 5] = std::array::from_fn(|k| {
          wide::u64(_mm256_or_si256(_mm256_srli_epi64(c[k].0, 1), _mm256_slli_epi64(ld(k, base + i + 1), 63)))
        });
        let w: [W; 5] = std::array::from_fn(|k| {
          wide::u64(_mm256_or_si256(_mm256_slli_epi64(c[k].0, 1), _mm256_srli_epi64(ld(k, base + i - 1), 63)))
        });
        let o = wide::step_planes(c, n, e, s, w);
        for k in 0..5 {
          _mm256_storeu_si256(dst.planes[k].as_mut_ptr().add(base + i) as *mut __m256i, o[k].0);
        }
      }
      i += 4;
    }
  }
}

/// Bit-sliced step: one call of the gate network per 64 cells.
#[inline(never)]
fn plane_step(src: &PlaneGrid, dst: &mut PlaneGrid) {
  let (h, ww) = (src.h, src.ww);
  assert!(dst.h == h && dst.ww == ww);
  let [d0, d1, d2, d3, d4] = &mut dst.planes;
  for y in 1..=h {
    let base = y * ww;
    let up: [&[u64]; 5] = std::array::from_fn(|k| &src.planes[k][base - ww..base]);
    let cur: [&[u64]; 5] = std::array::from_fn(|k| &src.planes[k][base..base + ww]);
    let dn: [&[u64]; 5] = std::array::from_fn(|k| &src.planes[k][base + ww..base + 2 * ww]);
    let o0 = &mut d0[base..base + ww];
    let o1 = &mut d1[base..base + ww];
    let o2 = &mut d2[base..base + ww];
    let o3 = &mut d3[base..base + ww];
    let o4 = &mut d4[base..base + ww];
    for i in 1..ww - 1 {
      let c: [u64; 5] = std::array::from_fn(|k| cur[k][i]);
      let n: [u64; 5] = std::array::from_fn(|k| up[k][i]);
      let s: [u64; 5] = std::array::from_fn(|k| dn[k][i]);
      // east neighbour of cell x is cell x+1 (bit i+1), west neighbour is cell x-1
      let e: [u64; 5] = std::array::from_fn(|k| (cur[k][i] >> 1) | (cur[k][i + 1] << 63));
      let w: [u64; 5] = std::array::from_fn(|k| (cur[k][i] << 1) | (cur[k][i - 1] >> 63));
      let o = step_planes(c, n, e, s, w);
      o0[i] = o[0];
      o1[i] = o[1];
      o2[i] = o[2];
      o3[i] = o[3];
      o4[i] = o[4];
    }
  }
}


//! Single-threaded CPU micro-benchmark for research/bitslice.
//!
//! Engines (all with a dead, all-zero boundary around the grid):
//!   * `lut`   one byte per cell, one load from the 2^25-entry table per cell
//!             (index = w | s<<5 | e<<10 | n<<15 | c<<20, exactly the GPU kernel's index);
//!   * `bits`  five bit-planes, the generated gate network `step_planes` on u64 words
//!             (64 cells per word operation);
//!   * `small` form C: four 1024-entry tables indexed by (centre, one neighbour) whose outputs
//!             are added to index one final table (about 15 KiB in total; `small.rs`);
//!   * `scalar` form A: the same gate network evaluated one cell at a time on the 25-bit index
//!             (generated by scalar.py; no table, no branch);
//!   * `wide`  only when built with AVX2 (`RUSTFLAGS="-C target-cpu=native"`): the same gate
//!             network on 256-bit words (`wide.rs`).
//!
//! Before anything is timed:
//!   1. `step_planes`, `scalar_step` and the small tables are checked against all 2^25 table entries;
//!   2. all engines are run side by side on the benchmark content and their grids compared.
//!
//! usage: bitslice-bench [--size N[,N..]] [--gens G] [--repeats R] [--pattern file.rle] [--lut file.bin]


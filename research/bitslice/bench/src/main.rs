struct Rng(u64);
impl Rng {
  fn next(&mut self) -> u64 {
    // xorshift64*
    self.0 ^= self.0 >> 12;
    self.0 ^= self.0 << 25;
    self.0 ^= self.0 >> 27;
    self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
  }
}

fn random_grid(w: usize, h: usize, seed: u64) -> ByteGrid {
  let mut g = ByteGrid::new(w, h);
  let mut r = Rng(seed);
  for y in 0..h {
    for x in 0..w {
      g.set(x, y, ((r.next() >> 40) & 31) as u8);
    }
  }
  g
}

/// Golly extended RLE (`.`/`b` = 0, `A`..`X` = 1..24, prefix `p`..`y` adds 24, 48, ...).
fn read_rle(path: &std::path::Path) -> (usize, usize, Vec<u8>) {
  let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
  let (mut w, mut h) = (0usize, 0usize);
  let mut data = String::new();
  let mut header_done = false;
  for line in text.lines() {
    let t = line.trim();
    if t.is_empty() || t.starts_with('#') {
      continue;
    }
    if !header_done {
      assert!(t.starts_with('x'), "RLE header expected");
      for part in t.split(',') {
        let mut kv = part.splitn(2, '=');
        let (k, v) = (kv.next().unwrap().trim(), kv.next().unwrap_or("").trim());
        match k {
          "x" => w = v.parse().unwrap(),
          "y" => h = v.parse().unwrap(),
          _ => {}
        }
      }
      header_done = true;
    } else {
      data.push_str(t);
    }
  }
  let mut cells = vec![0u8; w * h];
  let (mut x, mut y, mut count, mut prefix) = (0usize, 0usize, 0usize, 0u32);
  for ch in data.bytes() {
    match ch {
      b'0'..=b'9' => count = count * 10 + (ch - b'0') as usize,
      b'$' => {
        y += count.max(1);
        x = 0;
        count = 0;
      }
      b'!' => break,
      b'p'..=b'y' => prefix = (ch - b'p') as u32 + 1,
      b'.' | b'b' | b'o' | b'A'..=b'X' => {
        let s = match ch {
          b'.' | b'b' => 0,
          b'o' => 1,
          _ => prefix * 24 + (ch - b'A') as u32 + 1,
        };
        prefix = 0;
        let n = count.max(1);
        assert!(s < 32, "state {s} out of range");
        for i in 0..n {
          cells[y * w + x + i] = s as u8;
        }
        x += n;
        count = 0;
      }
      _ => {}
    }
  }
  (w, h, cells)
}

/// Fill a `size x size` grid with copies of the pattern, `gap` empty cells around each copy.
fn tiled_pattern(pw: usize, ph: usize, pat: &[u8], size: usize, gap: usize) -> (ByteGrid, usize) {
  let mut g = ByteGrid::new(size, size);
  let (cw, ch) = (pw + 2 * gap, ph + 2 * gap);
  let (nx, ny) = (size / cw, size / ch);
  for j in 0..ny {
    for i in 0..nx {
      for y in 0..ph {
        for x in 0..pw {
          g.set(i * cw + gap + x, j * ch + gap + y, pat[y * pw + x]);
        }
      }
    }
  }
  (g, nx * ny)
}


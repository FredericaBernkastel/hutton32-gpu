/// `step_planes` against every entry of the table (64 consecutive indices per call).
fn exhaustive_check(lut: &[u8; LUT_SIZE]) -> u64 {
  // plane of index bit j for the 64 indices base .. base+64
  let low: [u64; 6] = std::array::from_fn(|j| {
    let mut m = 0u64;
    for p in 0..64 {
      if (p >> j) & 1 == 1 {
        m |= 1 << p;
      }
    }
    m
  });
  let mut mismatches = 0u64;
  for block in 0..LUT_SIZE / 64 {
    let base = block * 64;
    let bit = |j: usize| -> u64 {
      if j < 6 {
        low[j]
      } else if (base >> j) & 1 == 1 {
        !0
      } else {
        0
      }
    };
    let field = |f: usize| -> [u64; 5] { std::array::from_fn(|k| bit(5 * f + k)) };
    // index = w | s<<5 | e<<10 | n<<15 | c<<20
    let (w, s, e, n, c) = (field(0), field(1), field(2), field(3), field(4));
    let o = step_planes(c, n, e, s, w);
    for p in 0..64 {
      let got = (0..5).fold(0u8, |acc, k| acc | ((((o[k] >> p) & 1) as u8) << k));
      if got != lut[base + p] {
        mismatches += 1;
      }
    }
  }
  mismatches
}

fn count_diff(a: &ByteGrid, b: &ByteGrid) -> usize {
  a.cells.iter().zip(&b.cells).filter(|(x, y)| x != y).count()
}


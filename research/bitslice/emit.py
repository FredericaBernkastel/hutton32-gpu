"""Generate `step_planes.wgsl` and `step_planes.rs` from a netlist file (see xag.Netlist).

usage: python emit.py [circuit.netlist]

The generated functions are straight-line code: one `let` per gate, operators ~ & | ^ only
(`!` instead of `~` in Rust).  Element k of each array argument is bit k of the cell state;
bit i of a word is cell i.
"""
from __future__ import annotations

import sys
from pathlib import Path

from xag import Netlist, HERE

SYM = {"AND": "&", "OR": "|", "XOR": "^"}


def _stats_line(nl: Netlist) -> str:
    c = nl.counts()
    return (f"{c['total']} gates (AND {c['AND']}, OR {c['OR']}, XOR {c['XOR']}, NOT {c['NOT']}), "
            f"depth {nl.depth()} ({nl.depth(False)} not counting NOT)")


def to_wgsl(nl: Netlist, source: str) -> str:
    L = []
    L.append(f"// Generated by research/bitslice/emit.py from {source} - do not edit.")
    L.append("// Hutton32b (Golly table, lut_table_Hutton32b.bin) as a bit-sliced gate network:")
    L.append(f"// {_stats_line(nl)}.")
    L.append("// Element k of each argument is bit k of the cell state for 32 cells (bit i = cell i).")
    L.append("fn step_planes(c: array<u32,5>, n: array<u32,5>, e: array<u32,5>, s: array<u32,5>, "
             "w: array<u32,5>) -> array<u32,5> {")
    ins = set(nl.inputs)

    def r(sig):  # inputs are read straight from the argument arrays: c0 -> c[0]
        return f"{sig[0]}[{sig[1]}]" if sig in ins else sig

    for name, op, a, b in nl.gates:
        if op == "NOT":
            L.append(f"  let {name} = ~{r(a)};")
        else:
            L.append(f"  let {name} = {r(a)} {SYM[op]} {r(b)};")
    const = {"0": "0u", "1": "0xffffffffu"}
    outs = [const.get(nl.outputs[f"o{k}"], r(nl.outputs[f"o{k}"])) for k in range(5)]
    L.append(f"  return array<u32,5>({', '.join(outs)});")
    L.append("}")
    return "\n".join(L) + "\n"


def to_rust(nl: Netlist, source: str) -> str:
    L = []
    L.append(f"// Generated by research/bitslice/emit.py from {source} - do not edit.")
    L.append("// Hutton32b (Golly table, lut_table_Hutton32b.bin) as a bit-sliced gate network:")
    L.append(f"// {_stats_line(nl)}.")
    L.append("// Element k of each argument is bit k of the cell state for 64 cells (bit i = cell i).")
    L.append("#[allow(clippy::all)]")
    L.append("#[inline(always)]")
    L.append("pub fn step_planes(c: [u64; 5], n: [u64; 5], e: [u64; 5], s: [u64; 5], w: [u64; 5]) -> [u64; 5] {")
    for p in "cnesw":
        L.append(f"    let [{', '.join(f'{p}{k}' for k in range(5))}] = {p};")
    for name, op, a, b in nl.gates:
        if op == "NOT":
            L.append(f"    let {name} = !{a};")
        else:
            L.append(f"    let {name} = {a} {SYM[op]} {b};")
    const = {"0": "0u64", "1": "!0u64"}
    outs = [const.get(nl.outputs[f"o{k}"], nl.outputs[f"o{k}"]) for k in range(5)]
    L.append(f"    [{', '.join(outs)}]")
    L.append("}")
    return "\n".join(L) + "\n"


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "circuit.netlist"
    nl = Netlist.from_text(src.read_text())
    (HERE / "step_planes.wgsl").write_text(to_wgsl(nl, src.name), newline="\n")
    (HERE / "step_planes.rs").write_text(to_rust(nl, src.name), newline="\n")
    print(f"wrote step_planes.wgsl, step_planes.rs: {_stats_line(nl)}")


if __name__ == "__main__":
    main()

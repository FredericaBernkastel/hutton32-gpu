"""Form A: a scalar, branch-free evaluation of one cell from the 25-bit vector
v = w | s<<5 | e<<10 | n<<15 | c<<20, built mechanically from circuit.netlist, counted and
verified on all 2^25 values of v.

Construction (32-bit operations only: shift, and, or, xor, not):

  1. extract the five states:                 4 shifts + 5 masks
  2. every signal of the gate network that depends on one cell only (the whole per-cell
     predicate decode) is one shift of a 32-bit constant by that cell's state:
         p = K >> state            (K = truth table of the predicate over the 32 states;
                                    bit 0 of p is the predicate, the other bits are ignored)
     Inverters on such signals are free (complement the constant).
  3. every remaining gate (it combines different cells) is one operation on those words;
  4. pack the five result bits:               o0&1 | (o1&1)<<1 | ...   = 5 masks, 4 shifts, 4 ors

usage: python scalar.py [circuit.netlist]      (prints the operation count and the check result,
                                                writes scalar_step.rs for the Rust benchmark)
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

from xag import HERE, LUT_PATH, Netlist

CELLS = "cnesw"
SHIFT = {"w": 0, "s": 5, "e": 10, "n": 15, "c": 20}


def build_program(nl: Netlist):
    """Returns (program, counts). Program statements:
       ('state', cell) | ('pred', name, cell, K) | ('gate', name, op, a, b)"""
    support = {}
    for name in nl.inputs:
        support[name] = {name[0]}
    for name, op, a, b in nl.gates:
        support[name] = support[a] | (support[b] if b is not None else set())
    # truth tables of single-cell signals: simulate with one cell's bits = the 32 states
    tt = {}
    for cell in CELLS:
        val = {}
        for name in nl.inputs:
            if name[0] == cell:
                k = int(name[1])
                val[name] = sum(1 << st for st in range(32) if (st >> k) & 1)
            else:
                val[name] = 0
        M = (1 << 32) - 1
        for name, op, a, b in nl.gates:
            if op == "NOT":
                val[name] = val[a] ^ M
            elif op == "AND":
                val[name] = val[a] & val[b]
            elif op == "OR":
                val[name] = val[a] | val[b]
            else:
                val[name] = val[a] ^ val[b]
        for name, sup in support.items():
            if sup == {cell}:
                tt[name] = (cell, val[name])
    single = set(tt)
    prog = [("state", c) for c in CELLS]
    emitted = set()

    def need(sig):
        if sig in single and sig not in emitted:
            cell, K = tt[sig]
            prog.append(("pred", sig, cell, K))
            emitted.add(sig)

    n_multi = 0
    for name, op, a, b in nl.gates:
        if name in single:
            continue
        need(a)
        if b is not None:
            need(b)
        prog.append(("gate", name, op, a, b))
        n_multi += 1
    for o in sorted(nl.outputs):
        need(nl.outputs[o])
    counts = {
        "extract states (4 shifts + 5 masks)": 9,
        "single-cell predicates (1 shift each)": len(emitted),
        "gates combining different cells": n_multi,
        "pack result (5 masks + 4 shifts + 4 ors)": 13,
    }
    counts["total"] = sum(counts.values())
    return prog, counts


def to_rust(prog, nl: Netlist, counts, source: str) -> str:
    """The same program as a Rust function (used by bench/ to time form A)."""
    sym = {"AND": "&", "OR": "|", "XOR": "^"}
    L = [
        f"// Generated by research/bitslice/scalar.py from {source} - do not edit.",
        f"// Form A: one cell per call from v = w | s<<5 | e<<10 | n<<15 | c<<20;",
        f"// {counts['total']} 32-bit operations, no branch, no table.",
        "#[allow(clippy::all)]",
        "#[inline(always)]",
        "pub fn scalar_step(v: u32) -> u32 {",
    ]
    for st in prog:
        if st[0] == "state":
            cell = st[1]
            sh = SHIFT[cell]
            L.append(f"    let st_{cell} = {'v' if sh == 0 else f'(v >> {sh})'} & 31;")
        elif st[0] == "pred":
            _, name, cell, K = st
            L.append(f"    let {name} = 0x{K:08x}u32 >> st_{cell};")
        else:
            _, name, op, a, b = st
            L.append(f"    let {name} = !{a};" if op == "NOT" else f"    let {name} = {a} {sym[op]} {b};")
    outs = [nl.outputs[f"o{k}"] for k in range(5)]
    assert all(o not in ("0", "1") for o in outs)
    L.append("    " + " | ".join(f"(({o} & 1) << {k})" if k else f"({o} & 1)" for k, o in enumerate(outs)))
    L.append("}")
    return "\n".join(L) + "\n"


def evaluate(prog, nl: Netlist, v: np.ndarray) -> np.ndarray:
    """Run the scalar program on an array of 25-bit vectors (uint32)."""
    val = {}
    state = {}
    for st in prog:
        if st[0] == "state":
            cell = st[1]
            state[cell] = (v >> np.uint32(SHIFT[cell])) & np.uint32(31)
        elif st[0] == "pred":
            _, name, cell, K = st
            val[name] = np.uint32(K) >> state[cell]
        else:
            _, name, op, a, b = st
            if op == "NOT":
                val[name] = ~val[a]
            elif op == "AND":
                val[name] = val[a] & val[b]
            elif op == "OR":
                val[name] = val[a] | val[b]
            else:
                val[name] = val[a] ^ val[b]
    out = np.zeros_like(v)
    for k in range(5):
        s = nl.outputs[f"o{k}"]
        bit = val[s] if s not in ("0", "1") else np.full_like(v, int(s))
        out |= (bit & np.uint32(1)) << np.uint32(k)
    return out


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "circuit.netlist"
    nl = Netlist.from_text(src.read_text())
    prog, counts = build_program(nl)
    lut = np.fromfile(LUT_PATH, dtype=np.uint8)
    bad = 0
    chunk = 1 << 20
    for base in range(0, 1 << 25, chunk):
        v = np.arange(base, base + chunk, dtype=np.uint32)
        got = evaluate(prog, nl, v)
        bad += int((got != lut[base:base + chunk]).sum())
    g = nl.counts()["total"]
    if bad == 0:
        (HERE / "scalar_step.rs").write_text(to_rust(prog, nl, counts, src.name), newline="\n")
    print(f"Form A (scalar, branch-free, one cell per evaluation), from {src.name}:")
    for k, n in counts.items():
        print(f"  {n:5d}  {k}")
    print(f"  check against all 2^25 table entries: {bad} mismatches")
    print(f"Form B for comparison: {g} gates per word -> {g / 32:.1f} ops/cell with 32-bit words, "
          f"{g / 64:.1f} with 64-bit words (plus about 30 shift/or ops per word to align E/W neighbours)")
    sys.exit(0 if bad == 0 else 1)


if __name__ == "__main__":
    main()
